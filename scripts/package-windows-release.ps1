param(
    [Parameter(Mandatory)][string]$Version,
    [Parameter(Mandatory)][string]$PublicKeyPath,
    [Parameter(Mandatory)][string]$ReleaseNotesPath,
    [Parameter(Mandatory)][string]$BuildToolsPath,
    [Parameter(Mandatory)][string]$LibClangPath,
    [Parameter(Mandatory)][string]$StageRoot,
    [Parameter(Mandatory)][string]$OutputDirectory
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
if ($env:OS -ne 'Windows_NT') { throw 'Release packaging requires Windows x64.' }
if ($Version -notmatch '^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$') { throw 'Use a stable three-part release version.' }
$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$node = (Get-Command node.exe -ErrorAction Stop).Source
$pnpm = (Get-Command pnpm.cmd -ErrorAction Stop).Source
$pnpmVersion = (& $pnpm --version).Trim()
if ($LASTEXITCODE -ne 0 -or $pnpmVersion -notmatch '^9\.') { throw 'Use pnpm 9 for this reviewed lockfile and package override configuration.' }
$null = Get-Command cargo.exe -ErrorAction Stop
$null = Get-Command rustc.exe -ErrorAction Stop
$keyFile = (Resolve-Path -LiteralPath $PublicKeyPath).Path
$notesFile = (Resolve-Path -LiteralPath $ReleaseNotesPath).Path
if (-not $env:TAURI_SIGNING_PRIVATE_KEY) { throw 'Provision TAURI_SIGNING_PRIVATE_KEY securely in this process before packaging. No signing key is generated by this script.' }
# Only the public key is read here. Tauri reads the private signing identity from
# its standard environment variables; neither key nor secret is printed.
$publicKey = [IO.File]::ReadAllText($keyFile).Trim()
if (-not $publicKey -or $publicKey.Length -gt 16384) { throw 'Invalid public signing key file.' }
$devShell = Join-Path $BuildToolsPath 'Common7\Tools\Microsoft.VisualStudio.DevShell.dll'
if (-not (Test-Path -LiteralPath $devShell -PathType Leaf)) { throw 'Microsoft C++ Build Tools are required.' }
if (-not (Test-Path -LiteralPath (Join-Path $LibClangPath 'libclang.dll') -PathType Leaf)) { throw 'Provide the LLVM directory containing libclang.dll.' }
foreach ($item in @($StageRoot, $OutputDirectory)) {
    if (-not [IO.Path]::IsPathRooted($item)) { throw 'StageRoot and OutputDirectory must be absolute paths.' }
    $absolute = [IO.Path]::GetFullPath($item).TrimEnd('\', '/')
    if ($absolute.StartsWith($repositoryRoot + '\', [StringComparison]::OrdinalIgnoreCase) -or $absolute -eq $repositoryRoot) { throw 'Release output and staging must be outside the source checkout.' }
    if ($absolute -match '(^|[\\/])OneDrive([^\\/]*)([\\/]|$)') { throw 'Keep release staging and output outside OneDrive.' }
    if (Test-Path -LiteralPath $absolute) { throw 'Use new staging and output directories; existing files will not be overwritten.' }
}
$StageRoot = [IO.Path]::GetFullPath($StageRoot)
$OutputDirectory = [IO.Path]::GetFullPath($OutputDirectory)
if ($OutputDirectory.StartsWith($StageRoot.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase) -or $StageRoot.StartsWith($OutputDirectory.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase) -or $StageRoot -eq $OutputDirectory) { throw 'StageRoot and OutputDirectory must be separate directories.' }
$changes = & git -C $repositoryRoot status --porcelain --untracked-files=normal
if ($LASTEXITCODE -ne 0 -or $changes) { throw 'Commit and review all intended source changes before release packaging; the checkout must be clean.' }
$commit = (& git -C $repositoryRoot rev-parse HEAD).Trim()
if ($LASTEXITCODE -ne 0) { throw 'Could not identify the source commit.' }
New-Item -ItemType Directory -Path $StageRoot | Out-Null
New-Item -ItemType Directory -Path $OutputDirectory | Out-Null
$sourceRoot = Join-Path $StageRoot 'source'
$archive = Join-Path $StageRoot 'source.zip'
& git -C $repositoryRoot archive --format=zip "--output=$archive" HEAD
if ($LASTEXITCODE -ne 0) { throw 'Could not create the committed source archive.' }
Expand-Archive -LiteralPath $archive -DestinationPath $sourceRoot
Remove-Item -LiteralPath $archive
$feedScript = Join-Path $sourceRoot 'scripts\windows-update-feed.cjs'
& $node $feedScript prepare-stage $sourceRoot $Version
if ($LASTEXITCODE -ne 0) { throw 'Portable release configuration failed validation.' }
$nativeRoot = Join-Path $sourceRoot 'frontend\src-tauri'
$frontendRoot = Join-Path $sourceRoot 'frontend'
$crtTarget = Join-Path $nativeRoot 'binaries\msvc-runtime'
New-Item -ItemType Directory -Path $crtTarget -Force | Out-Null
$redistRoot = Join-Path $BuildToolsPath 'VC\Redist\MSVC'
$redist = Get-ChildItem -LiteralPath $redistRoot -Directory | Where-Object { $_.Name -match '^\d+\.\d+\.\d+$' } | Sort-Object { [version]$_.Name } -Descending | Select-Object -First 1
if (-not $redist) { throw 'Microsoft release C++ redistributables were not found.' }
$crtFiles = @(Get-ChildItem -LiteralPath (Join-Path $redist.FullName 'x64\Microsoft.VC143.CRT') -Filter '*.dll' -File)
if ($crtFiles.Count -eq 0) { throw 'Microsoft release C++ runtime DLLs were not found.' }
foreach ($file in $crtFiles) {
    $signature = Get-AuthenticodeSignature -LiteralPath $file.FullName
    if ($signature.Status -ne 'Valid' -or $signature.SignerCertificate.Subject -notmatch 'O=Microsoft Corporation') { throw 'Microsoft runtime verification failed.' }
    Copy-Item -LiteralPath $file.FullName -Destination (Join-Path $crtTarget $file.Name)
}
Import-Module $devShell
Enter-VsDevShell -VsInstallPath $BuildToolsPath -SkipAutomaticLocation -DevCmdArguments '-arch=x64 -host_arch=x64' | Out-Null
$environment = @{
    OATS_UPDATER_PUBLIC_KEY = $publicKey
    CARGO_TARGET_DIR = (Join-Path $StageRoot 'target')
    CARGO_BUILD_JOBS = '1'
    CMAKE_BUILD_PARALLEL_LEVEL = '1'
    NEXT_TELEMETRY_DISABLED = '1'
    CARGO_PROFILE_RELEASE_DEBUG = '0'
    LIBCLANG_PATH = $LibClangPath
    ORT_LIB_LOCATION = (Join-Path $nativeRoot 'binaries\onnxruntime')
    WHISPER_DONT_GENERATE_BINDINGS = $null
}
$previous = @{}
foreach ($name in $environment.Keys) {
    $previous[$name] = [Environment]::GetEnvironmentVariable($name, 'Process')
    if ($null -eq $environment[$name]) {
        # whisper-rs tests whether the variable exists, including an empty
        # value. New PowerShell/.NET versions can preserve an empty variable
        # when SetEnvironmentVariable receives $null; remove it explicitly.
        Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
    } else {
        [Environment]::SetEnvironmentVariable($name, $environment[$name], 'Process')
    }
}
Push-Location $frontendRoot
try {
    & $node -e 'if (Object.hasOwn(process.env, "WHISPER_DONT_GENERATE_BINDINGS")) { console.error("Windows releases must generate native Whisper bindings; the disable flag must be absent, not empty."); process.exit(1); }'
    if ($LASTEXITCODE -ne 0) { throw 'Windows binding environment preflight failed.' }
    & $pnpm install --frozen-lockfile
    if ($LASTEXITCODE -ne 0) { throw 'Frozen frontend dependency installation failed.' }
    $frontendTests = @(Get-ChildItem -LiteralPath (Join-Path $frontendRoot 'tests/lib') -Filter '*.cjs' -File | ForEach-Object FullName) + @(Get-ChildItem -LiteralPath (Join-Path $frontendRoot 'tests/components') -Filter '*.cjs' -File | ForEach-Object FullName)
    & $node --test (Join-Path $sourceRoot 'scripts/windows-update-feed.test.cjs') @frontendTests
    if ($LASTEXITCODE -ne 0) { throw 'Release regression checks failed. No installer was published.' }
    & cargo test --locked --manifest-path (Join-Path $nativeRoot 'capture-core-tests/Cargo.toml') --lib
    if ($LASTEXITCODE -ne 0) { throw 'Bundled recording-worker regression checks failed. No installer was published.' }
    $policyTests = Join-Path $StageRoot 'updater-policy-tests.exe'
    & rustc --test --edition=2021 (Join-Path $nativeRoot 'src/updates/policy.rs') -o $policyTests
    if ($LASTEXITCODE -ne 0) { throw 'Updater policy tests did not compile.' }
    & $policyTests
    if ($LASTEXITCODE -ne 0) { throw 'Updater policy tests failed. No installer was published.' }
    $cli = Join-Path $frontendRoot 'node_modules\@tauri-apps\cli\tauri.js'
    $signerHelp = & $node $cli signer sign --help
    if ($LASTEXITCODE -ne 0 -or ($signerHelp -join "`n") -notmatch '\-\-app-version') { throw 'The frozen Tauri CLI lacks signed-version support. Upgrade and review its package lock before releasing.' }
    # CLI signing needs the public key in configuration as well as native env.
    $signingConfig = @{ plugins = @{ updater = @{ pubkey = $publicKey; requireSignedVersion = $true } } } | ConvertTo-Json -Depth 5 -Compress
    & $node $cli build --target x86_64-pc-windows-msvc --bundles nsis --config $signingConfig -- --locked -j 1
    if ($LASTEXITCODE -ne 0) { throw 'Signed Windows release build failed.' }
    $asset = "oats_${Version}_x64-setup.exe"
    $bundle = Join-Path $env:CARGO_TARGET_DIR "x86_64-pc-windows-msvc\release\bundle\nsis\$asset"
    Copy-Item -LiteralPath $bundle -Destination (Join-Path $OutputDirectory $asset)
    Copy-Item -LiteralPath "$bundle.sig" -Destination (Join-Path $OutputDirectory "$asset.sig")
    & $node $feedScript create $Version (Join-Path $OutputDirectory $asset) $keyFile $notesFile $OutputDirectory
    if ($LASTEXITCODE -ne 0) { throw 'Signed release/feed verification failed. Do not publish these files.' }
    [IO.File]::WriteAllText((Join-Path $OutputDirectory 'SOURCE-COMMIT.txt'), "$commit`n", [Text.UTF8Encoding]::new($false))
    Write-Host "Verified local release files: $OutputDirectory"
    Write-Host "No publication or installation was performed. Build staging remains at $StageRoot for inspection; remove it after acceptance."
} finally {
    Pop-Location
    foreach ($name in $previous.Keys) {
        if ($null -eq $previous[$name]) {
            Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
        } else {
            [Environment]::SetEnvironmentVariable($name, $previous[$name], 'Process')
        }
    }
}
